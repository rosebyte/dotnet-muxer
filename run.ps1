param(
    [Parameter(Mandatory = $true)]
    [ValidateSet("install", "uninstall", "build")]
    [string]$Action
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$MuxerDir = Join-Path $HOME ".dotnet-muxer"
$BeginMarker = "# >>> dotnet-muxer (generated by https://github.com/user/dotnet-muxer) >>>"
$EndMarker = "# <<< dotnet-muxer <<<"

function Get-ProfilePath {
    $homeProfilePath = Join-Path $HOME ".profile.ps1"
    if (Test-Path $homeProfilePath) {
        return $homeProfilePath
    }

    return $PROFILE.CurrentUserAllHosts
}

function Get-CandidateProfilePath {
    # Every profile file the muxer block could plausibly live in. Cleaning all of
    # them on install/uninstall prevents a stale copy in one file from running
    # alongside a fresh copy in another (which caused the self-referential
    # `code` wrapper to recurse into a call-depth overflow).
    $candidates = @(
        (Join-Path $HOME ".profile.ps1")
        $PROFILE.CurrentUserAllHosts
        $PROFILE.CurrentUserCurrentHost
    )

    return $candidates | Where-Object { $_ } | Select-Object -Unique
}

function Remove-MuxerBlock {
    param([string]$Path)

    if (-not (Test-Path $Path)) {
        return $false
    }

    $content = Get-Content $Path -Raw
    if ($null -eq $content -or $content -notmatch "dotnet-muxer") {
        return $false
    }

    $content = $content -replace "(?s)\r?\n?$([regex]::Escape($BeginMarker)).*?$([regex]::Escape($EndMarker))", ""
    Set-Content $Path -Value $content -NoNewline
    return $true
}

function Get-Rid {
    if ($IsWindows) { return "win-x64" }
    if ($IsMacOS) { return "osx-arm64" }
    return "linux-x64"
}

function Get-TargetFramework {
    $sdkLines = dotnet --list-sdks
    $majors = @()

    foreach ($line in $sdkLines) {
        if ($line -match '^\s*(\d+)\.') {
            $majors += [int]$Matches[1]
        }
    }

    if ($majors.Count -eq 0) {
        throw "Could not determine installed .NET SDK version from 'dotnet --list-sdks'"
    }

    $latest = ($majors | Measure-Object -Maximum).Maximum
    return "net$latest.0"
}

function Build-DotnetMuxer {
    $rid = Get-Rid
    $tfm = Get-TargetFramework
    dotnet publish (Join-Path $Root "src/DotnetMuxer/DotnetMuxer.csproj") -c Release -r $rid -p:BuildTargetFramework=$tfm
    exit $LASTEXITCODE
}

function Install-DotnetMuxer {
    $rid = Get-Rid
    $tfm = Get-TargetFramework
    $binaryName = if ($IsWindows) { "DotnetMuxer.exe" } else { "DotnetMuxer" }
    $installedName = if ($IsWindows) { "dotnet.exe" } else { "dotnet" }

    Write-Host "Building dotnet-muxer..."
    dotnet publish (Join-Path $Root "src/DotnetMuxer/DotnetMuxer.csproj") -c Release -r $rid -p:BuildTargetFramework=$tfm
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    Write-Host "Installing to $MuxerDir..."
    New-Item -ItemType Directory -Force -Path $MuxerDir | Out-Null
    Copy-Item (Join-Path $Root "src/DotnetMuxer/bin/Release/$tfm/$rid/publish/$binaryName") (Join-Path $MuxerDir $installedName) -Force

    $ProfilePath = Get-ProfilePath
    $ProfileDir = Split-Path $ProfilePath -Parent
    if (-not (Test-Path $ProfileDir)) {
        New-Item -ItemType Directory -Force -Path $ProfileDir | Out-Null
    }

    $Block = @"

$BeginMarker
if (-not (Test-Path Variable:Global:__dotnet_muxer_prev_code)) {
    `$Global:__dotnet_muxer_prev_code = if (Test-Path Function:\code) { Get-Item Function:\code } else { `$null }
}
function __dotnet_muxer_resolve_repo_dir {
    param([string]`$InputPath)

    if ([string]::IsNullOrWhiteSpace(`$InputPath) -or `$InputPath.StartsWith("-")) {
        return `$null
    }

    if (Test-Path `$InputPath -PathType Container) {
        return (Resolve-Path `$InputPath).Path
    }

    `$candidate = Join-Path `$HOME `$InputPath
    if (Test-Path `$candidate -PathType Container) {
        return (Resolve-Path `$candidate).Path
    }

    `$candidate = Join-Path `$HOME (Join-Path "Code" `$InputPath)
    if (Test-Path `$candidate -PathType Container) {
        return (Resolve-Path `$candidate).Path
    }

    `$candidate = Join-Path `$HOME (Join-Path "Code" "dotnet-`$InputPath")
    if (Test-Path `$candidate -PathType Container) {
        return (Resolve-Path `$candidate).Path
    }

    return `$null
}
function code {
    `$repoRoot = if (`$args.Count -ge 1) { __dotnet_muxer_resolve_repo_dir `$args[0] } else { `$null }
    if (`$repoRoot) {
        `$muxerTargetExe = Join-Path `$repoRoot ".dotnet\dotnet.exe"
        `$muxerTarget = Join-Path `$repoRoot ".dotnet\dotnet"
        if (Test-Path `$muxerTargetExe) {
            `$env:DOTNET_MUXER_TARGET = `$muxerTargetExe
            `$env:PATH = "`$HOME\.dotnet-muxer;`$env:PATH"
            `$env:DOTNET_MULTILEVEL_LOOKUP = "0"
            `$env:BuildTargetFramework = "net11.0"
        } elseif (Test-Path `$muxerTarget) {
            `$env:DOTNET_MUXER_TARGET = `$muxerTarget
            `$env:PATH = "`$HOME\.dotnet-muxer;`$env:PATH"
            `$env:DOTNET_MULTILEVEL_LOOKUP = "0"
            `$env:BuildTargetFramework = "net11.0"
        }
    }
    if (`$Global:__dotnet_muxer_prev_code) {
        & `$Global:__dotnet_muxer_prev_code @args
    } else {
        & (Get-Command code.cmd -CommandType Application | Select-Object -First 1) @args
    }
}
function runtime {
    param([string]`$Target)
    if (`$Target -eq "vs") {
        if (-not (Test-Path `$env:RUNTIME_ROOT)) {
            Write-Host "RUNTIME_ROOT does not exist: `$env:RUNTIME_ROOT" -ForegroundColor Red
            return
        }
        `$muxerTargetExe = Join-Path `$env:RUNTIME_ROOT ".dotnet\dotnet.exe"
        `$muxerTarget = Join-Path `$env:RUNTIME_ROOT ".dotnet\dotnet"
        if (Test-Path `$muxerTargetExe) {
            `$env:DOTNET_MUXER_TARGET = `$muxerTargetExe
            `$env:PATH = "`$HOME\.dotnet-muxer;`$env:PATH"
            `$env:DOTNET_MULTILEVEL_LOOKUP = "0"
            `$env:BuildTargetFramework = "net11.0"
        } elseif (Test-Path `$muxerTarget) {
            `$env:DOTNET_MUXER_TARGET = `$muxerTarget
            `$env:PATH = "`$HOME\.dotnet-muxer;`$env:PATH"
            `$env:DOTNET_MULTILEVEL_LOOKUP = "0"
            `$env:BuildTargetFramework = "net11.0"
        }
        `$vsPath = & "`${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe" -latest -property installationPath 2>`$null
        if (-not `$vsPath) {
            Write-Host "Could not find Visual Studio via vswhere" -ForegroundColor Red
            return
        }
        `$devenv = Join-Path `$vsPath "Common7\IDE\devenv.exe"
        Write-Host "Opening Visual Studio in `$env:RUNTIME_ROOT..."
        Start-Process `$devenv -WorkingDirectory `$env:RUNTIME_ROOT
    } else {
        Write-Host "Usage: runtime vs" -ForegroundColor Yellow
    }
}
$EndMarker
"@

    if (Test-Path $ProfilePath) {
        $content = Get-Content $ProfilePath -Raw
        if ($content -match "dotnet-muxer") {
            Write-Host "Refreshing dotnet-muxer block in $ProfilePath"
        } else {
            Write-Host "Adding dotnet-muxer block to $ProfilePath"
        }
    } else {
        Write-Host "Creating $ProfilePath"
    }

    # Strip any existing block from every candidate profile first. A leftover copy
    # in a different file would run again in the same session and make the `code`
    # wrapper capture itself, recursing until PowerShell aborts with a call-depth
    # overflow.
    foreach ($candidate in Get-CandidateProfilePath) {
        if ((Remove-MuxerBlock $candidate) -and ($candidate -ne $ProfilePath)) {
            Write-Host "Removed stale dotnet-muxer block from $candidate"
        }
    }

    Add-Content $ProfilePath -Value $Block

    Write-Host ""
    Write-Host "Done. When you run 'code /path/to/repo' and the repo has .dotnet/dotnet.exe,"
    Write-Host "VSCode will automatically use the muxer with the correct target."
    Write-Host ""
    Write-Host "Optional: `$env:DOTNET_MUXER_VERBOSE = '1'  (logs to $MuxerDir\log.log)"
    exit 0
}

function Uninstall-DotnetMuxer {
    Remove-Item -ErrorAction SilentlyContinue -Force @(
            (Join-Path $MuxerDir "dotnet.exe"),
            (Join-Path $MuxerDir "dotnet"),
            (Join-Path $MuxerDir "log.log")
        )

    foreach ($candidate in Get-CandidateProfilePath) {
        if (Remove-MuxerBlock $candidate) {
            Write-Host "Removed dotnet-muxer block from $candidate"
        }
    }

    Write-Host "Uninstalled dotnet-muxer from $MuxerDir and removed shell hooks from PowerShell profile"
    exit 0
}

switch ($Action) {
    "install" {
        Install-DotnetMuxer
    }
    "uninstall" {
        Uninstall-DotnetMuxer
    }
    "build" {
        Build-DotnetMuxer
    }
}
